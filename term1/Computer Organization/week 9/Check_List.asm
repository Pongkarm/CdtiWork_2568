        .ORIG   x3000

        AND     R0, R0, #0      ; R0 = 0
        ADD     R0, R0, #1      ; R0 = 1 (สมมติว่า "พบ 5")

        AND     R1, R1, #0
        ADD     R1, R1, #-5     ; R1 = -5 (สำหรับตรวจว่า R2 == 5)

        AND     R3, R3, #0
        ADD     R3, R3, #10     ; R3 = จำนวนสมาชิก (10 ตัว)

        LD      R4, PTR         ; R4 = x3100 (เริ่มชี้อาร์เรย์)
        LDR     R2, R4, #0      ; โหลดค่าแรกเข้ามาใน R2

LOOP    ADD     R2, R2, R1      ; R2 + (-5)
        BRz     DONE            ; ถ้าเป็นศูนย์ แสดงว่า R2 เดิมคือ 5 -> เจอแล้ว

        ADD     R4, R4, #1      ; ชี้ไปที่สมาชิกถัดไป
        ADD     R3, R3, #-1     ; ลด counter
        LDR     R2, R4, #0      ; โหลดค่าใหม่
        BRp     LOOP            ; ถ้า counter > 0 ให้ทำต่อ

        AND     R0, R0, #0      ; ถ้า loop หมดแล้วยังไม่เจอ -> R0 = 0

DONE    HALT

PTR     .FILL   x3100           ; เก็บตำแหน่งเริ่มต้นของอาร์เรย์

